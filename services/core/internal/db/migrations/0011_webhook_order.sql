-- Webhook ordering and replay (docs/05-integration.md §4).
--
-- subject_id is the record an event is about when order matters between its
-- events: the attempt, for attempt.* events. seq orders events within it,
-- since created_at can tie. A delivery waits while an earlier pending
-- delivery of the same subject to the same endpoint is still to be sent, and
-- a replay of one attempt finds its events by subject.
ALTER TABLE webhook_events
  ADD COLUMN subject_id uuid,
  ADD COLUMN seq bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX webhook_events_subject_idx ON webhook_events (subject_id, seq) WHERE subject_id IS NOT NULL;
