/**
 * The candidate runner's build: its own entry, its own chunks under take/, and
 * a service worker that keeps the app shell on the device.
 *
 * Run after the studio's build into the same directory (bun run build does).
 */
import { defineConfig, type Plugin } from 'vite'
import { createHash } from 'node:crypto'
import { deflateSync } from 'node:zlib'
import { readFileSync } from 'node:fs'
import { base } from './vite.config'

/**
 * take/sw.js with the exact files this build produced, and a cache name that
 * changes whenever they do, so a new deploy replaces the old shell in one step.
 */
function shell(): Plugin {
  return {
    name: 'am-runner-shell',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = Object.keys(bundle)
        .filter((f) => f.startsWith('take/assets/') && !/^take\/assets\/vision[-.]/.test(f) && !f.endsWith('.map'))
        .map((f) => `/${f}`)
        .sort()
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12)
      const sw = SW.replace('__VERSION__', version).replace('__FILES__', JSON.stringify(['/take/', ...files]))
      // A worker that does not parse is a runner that never works offline, silently: fail the build instead.
      new Function(sw)
      this.emitFile({ type: 'asset', fileName: 'take/sw.js', source: sw })
      this.emitFile({ type: 'asset', fileName: 'take/manifest.webmanifest', source: MANIFEST })
      for (const n of [192, 512]) this.emitFile({ type: 'asset', fileName: `take/icon-${n}.png`, source: icon(n) })
    },
  }
}

/*
 * The tier 2 face check's runtime and model, copied as-is under a path that
 * changes with their content (so they can be cached for good), and named to
 * the code through __AM_VISION__. The service worker keeps them once fetched;
 * they are not precached, since only a tier 2 attempt needs them.
 */
const VISION_FILES: [string, string][] = [
  // The module flavour, for the detector's module worker (src/backend/vision.worker.ts).
  ['vision_wasm_module_internal.js', 'node_modules/@mediapipe/tasks-vision/wasm/vision_wasm_module_internal.js'],
  ['vision_wasm_module_internal.wasm', 'node_modules/@mediapipe/tasks-vision/wasm/vision_wasm_module_internal.wasm'],
  ['blaze_face_short_range.tflite', 'vendor/blaze_face_short_range.tflite'],
]
const visionSum = createHash('sha256')
for (const [, from] of VISION_FILES) visionSum.update(readFileSync(new URL(from, import.meta.url)))
const VISION = `/take/assets/vision-${visionSum.digest('hex').slice(0, 12)}`

function vision(): Plugin {
  return {
    name: 'am-runner-vision',
    apply: 'build',
    generateBundle() {
      for (const [name, from] of VISION_FILES)
        this.emitFile({ type: 'asset', fileName: `${VISION.slice(1)}/${name}`, source: readFileSync(new URL(from, import.meta.url)) })
    },
  }
}

export default defineConfig({
  ...base,
  define: { __AM_VISION__: JSON.stringify(VISION) },
  plugins: [...base.plugins, shell(), vision()],
  build: {
    emptyOutDir: false,
    assetsDir: 'take/assets',
    rollupOptions: { input: { runner: 'take/index.html' } },
  },
})

const MANIFEST = JSON.stringify(
  {
    name: 'AssessMatrix',
    short_name: 'AssessMatrix',
    start_url: '/take/',
    scope: '/take/',
    display: 'standalone',
    background_color: '#ffffff',
    theme_color: '#2470cc',
    icons: [192, 512].map((n) => ({ src: `/take/icon-${n}.png`, sizes: `${n}x${n}`, type: 'image/png', purpose: 'any maskable' })),
  },
  null,
  2,
)

/*
 * The service worker. It never caches an RPC: a cached response would be a
 * lie about the server. It sends one, AppendEvents, when a background sync
 * fires (below). It keeps three things:
 *   - the shell (index + hashed assets), so a reload with no network still
 *     opens the exam and its queued answers;
 *   - images the exam has shown, so they still show after an offline reload;
 *   - the tier 2 face check's runtime, once a tier 2 attempt has fetched it;
 *   - nothing else.
 */
const SW = `/* generated by vite.runner.config.ts */
const SHELL = 'am-runner-__VERSION__'
const MEDIA = 'am-media-v1'
const VISION = 'am-vision-v1'
const FILES = __FILES__

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('am-runner-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('message', (e) => {
  // The session ended on this device: its images are no one else's business.
  if (e.data === 'forget-media') e.waitUntil(caches.delete(MEDIA))
})

/*
 * Background Sync: the runner asks for one whenever a send fails, so answers
 * waiting on the device reach the server once the network is back, even if
 * the candidate has closed the tab or the browser was killed.
 *
 * It sends the queue's sealed batches as they are on disk (src/backend/sync.ts),
 * oldest first, and writes nothing: each batch keeps its id, so the server
 * stores it once, whether this or a runner tab sends it first. It takes the
 * same Web Lock the tab sends under, so the two never interleave, and tells
 * any open runner tab to send too, for what it has not sealed yet. A sync
 * that cannot reach the server fails, and the browser tries it again later.
 */
self.addEventListener('sync', (e) => {
  if (e.tag === 'am-queue') e.waitUntil(deliver())
})

async function deliver() {
  for (const c of await self.clients.matchAll({ type: 'window' })) if (new URL(c.url).pathname.startsWith('/take')) c.postMessage('am-flush')
  const root = await navigator.storage.getDirectory()
  const ids = new Set()
  for await (const name of root.keys()) {
    const m = /^am\\.pending\\.v1\\.(.+)\\.[ab]$/.exec(name)
    if (m) ids.add(m[1])
  }
  let retry = false
  for (const id of ids) {
    const sent = await navigator.locks.request('am.send.' + id, () => send(root, id))
    if (sent === 'retry') retry = true
  }
  // A rejected sync is tried again by the browser, later.
  if (retry) throw new Error('the server is not reachable yet')
}

/** The newest whole slot of a queue, as opfs.worker.ts writes them: <seq>\\n<json>. */
async function slot(root, name) {
  try {
    const raw = await (await (await root.getFileHandle(name)).getFile()).text()
    const nl = raw.indexOf('\\n')
    const seq = Number(raw.slice(0, nl))
    if (nl < 0 || !Number.isSafeInteger(seq)) return null
    const text = raw.slice(nl + 1)
    return { seq, q: text === '' ? null : JSON.parse(text) }
  } catch (err) {
    // Missing, or torn mid-write: the other slot has it. Busy: try again later.
    return err && (err.name === 'NotFoundError' || err.name === 'SyntaxError') ? null : 'busy'
  }
}

async function send(root, id) {
  const [a, b] = await Promise.all([slot(root, 'am.pending.v1.' + id + '.a'), slot(root, 'am.pending.v1.' + id + '.b')])
  if (a === 'busy' || b === 'busy') return 'retry'
  const newest = !a ? b : !b ? a : a.seq >= b.seq ? a : b
  const q = newest && newest.q
  if (!q) return 'done'
  // A queue saved before batches were sealed has at most one, in flight.
  const batches = [...(q.inflight ? [q.inflight] : []), ...(q.batches || [])]
  for (const batch of batches) {
    let res
    try {
      res = await fetch('/assessmatrix.v1.CandidateService/AppendEvents', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Connect-Protocol-Version': '1' },
        body: JSON.stringify({ attemptId: id, batchId: batch.batchId, events: batch.events.map(wire) }),
        // Never hold the lock on a connection that went quiet: the tab may want it.
        signal: AbortSignal.timeout(20000),
      })
    } catch {
      return 'retry'
    }
    if (res.status >= 500 || res.status === 408 || res.status === 429) return 'retry'
    // Signed out, submitted, refused: the reopened tab knows what to do with it.
    if (!res.ok) return 'done'
  }
  return 'done'
}

/** One queued event as AppendEvents takes it in JSON, as the tab's client sends it. */
function wire(e) {
  const f = e.file
  return {
    kind: e.kind,
    itemId: e.itemId || '',
    values: e.values || [],
    text: e.text || '',
    file: f ? { id: f.id, url: f.url, alt: f.alt, w: f.w, h: f.h, bytes: String(Math.round(f.bytes)) } : undefined,
    detail: e.detail || '',
    clientTime: String(e.clientTime),
  }
}

self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== location.origin) return

  if (req.mode === 'navigate' && url.pathname.startsWith('/take')) {
    // The newest shell when there is a network; the cached one when there is not.
    e.respondWith(
      fetch(req).catch(() => caches.open(SHELL).then((c) => c.match('/take/')).then((r) => r || Response.error())),
    )
    return
  }
  if (FILES.includes(url.pathname)) {
    e.respondWith(caches.open(SHELL).then((c) => c.match(url.pathname).then((hit) => hit || fetch(req))))
    return
  }
  if (url.pathname.startsWith('/take/assets/vision-') || url.pathname.startsWith('/take/assets/vision.')) {
    // Content-addressed: once fetched it never changes, so the cache answers first.
    e.respondWith(
      caches.open(VISION).then((c) =>
        c.match(req).then(
          (hit) =>
            hit ||
            fetch(req).then((res) => {
              if (res.ok) c.put(req, res.clone())
              return res
            }),
        ),
      ),
    )
    return
  }
  if (url.pathname.startsWith('/media/')) {
    e.respondWith(
      caches.open(MEDIA).then((c) =>
        fetch(req)
          .then((res) => {
            if (res.ok) c.put(req, res.clone())
            return res
          })
          .catch(() => c.match(req).then((hit) => hit || Response.error())),
      ),
    )
  }
})
`

/** The install icon: a brand-blue tile with a white check, drawn here so no binary lives in the repo. */
function icon(n: number): Uint8Array {
  const blue = [0x24, 0x70, 0xcc]
  const raw = Buffer.alloc((n * 3 + 1) * n)
  // A check mark: two strokes, in tile-relative coordinates.
  const near = (x: number, y: number, [ax, ay]: number[], [bx, by]: number[], w: number) => {
    const dx = bx! - ax!
    const dy = by! - ay!
    const t = Math.max(0, Math.min(1, ((x - ax!) * dx + (y - ay!) * dy) / (dx * dx + dy * dy)))
    return Math.hypot(x - (ax! + t * dx), y - (ay! + t * dy)) < w
  }
  for (let y = 0; y < n; y++) {
    raw[y * (n * 3 + 1)] = 0
    for (let x = 0; x < n; x++) {
      const u = x / n
      const v = y / n
      const white = near(u, v, [0.3, 0.52], [0.44, 0.66], 0.05) || near(u, v, [0.44, 0.66], [0.72, 0.36], 0.05)
      const o = y * (n * 3 + 1) + 1 + x * 3
      raw[o] = white ? 255 : blue[0]!
      raw[o + 1] = white ? 255 : blue[1]!
      raw[o + 2] = white ? 255 : blue[2]!
    }
  }
  const crcTable = Array.from({ length: 256 }, (_, k) => {
    let c = k
    for (let i = 0; i < 8; i++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    return c >>> 0
  })
  const crc = (b: Buffer) => {
    let c = ~0
    for (const x of b) c = crcTable[(c ^ x) & 0xff]! ^ (c >>> 8)
    return ~c >>> 0
  }
  const chunk = (type: string, data: Buffer) => {
    const len = Buffer.alloc(4)
    len.writeUInt32BE(data.length)
    const body = Buffer.concat([Buffer.from(type), data])
    const sum = Buffer.alloc(4)
    sum.writeUInt32BE(crc(body))
    return Buffer.concat([len, body, sum])
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(n, 0)
  ihdr.writeUInt32BE(n, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 2 // truecolour
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ])
}
